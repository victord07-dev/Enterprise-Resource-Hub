export function generatePricingPDF(products: PricingProductPDF[], portfolio: PortfolioPDF, filterDesc: string): Blob {
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  let y = drawHeader(doc, "Daily Pricing Report", filterDesc || "FIFO Pricing & Margin Summary");

  y = drawSummaryBand(doc, [
    { label: "Inventory Cost", value: portfolio.totalInventoryCost, color: C.textPrimary },
    { label: "Revenue @ Conf. Prices", value: portfolio.revenueAtConfirmedPrices, color: C.green },
    { label: "Required @ Min Margin", value: portfolio.requiredRevenueAtMinMargin, color: C.amber },
  ], y + 2);

  const cols: ColDef[] = [
    { header: "Product", width: 40 },
    { header: "SKU", width: 22 },
    { header: "Category", width: 24 },
    { header: "Stock", width: 18, align: "right" },
    { header: "Blended Cost", width: 25, align: "right" },
    { header: "Global Floor", width: 25, align: "right" },
    { header: "Strict Floor", width: 25, align: "right" },
    { header: "Eff. Price", width: 25, align: "right" },
    { header: "Margin %", width: 18, align: "right" },
    { header: "Risk", width: 18, align: "center" },
    { header: "Source", width: 18, align: "center" },
    { header: "Status", width: 19, align: "center" },
  ];

  const tableRows = products.map(p => [
    (p.sellPriority ? "\uD83D\uDD25 " : "") + p.productName,
    p.sku,
    p.category,
    `${p.totalStock.toLocaleString()} ${p.unit}`,
    p.blendedCost !== null ? fmtINR(p.blendedCost) : "\u2014",
    p.globalFloor !== null ? fmtINR(p.globalFloor) : "\u2014",
    p.strictFloor !== null ? fmtINR(p.strictFloor) : "\u2014",
    fmtINR(p.confirmedPrice),
    p.marginPct !== null ? `${p.marginPct.toFixed(1)}%` : "\u2014",
    p.pressureLevel,
    p.source === "today" ? "Today" : p.source === "fallback" ? "Fallback" : "No Price",
    p.hasConfirmedToday ? "Confirmed" : p.hasUnconfirmedSheet ? "Pending" : "No Sheet",
  ]);

  drawTable(doc, cols, tableRows, y + 2, (i, row) => {
    const pressure = products[i]?.pressureLevel;
    if (pressure === "High Risk") return [255, 245, 245] as [number, number, number];
    return null;
  });

  addPageFooter(doc);
  return doc.output("blob");
}
